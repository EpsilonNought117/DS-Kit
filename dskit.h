#ifndef DSKIT_ASSERT
#define DSKIT_ASSERT(expr)                    \
    do                                        \
    {                                         \
        if (!(expr))                          \
        {                                     \
            fprintf(                          \
                stderr,                       \
                "\nDSKIT ASSERTION FAILED!\n" \
                "ASSERTION: %s\n"             \
                "FILE: %s\nLINE: %d\n"        \
                "EXITING ...\n\n",            \
                #expr, __FILE__, __LINE__);   \
            exit(EXIT_FAILURE);               \
        }                                     \
    } while (0)
#endif

